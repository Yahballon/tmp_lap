#!/usr/bin/env python3
"""Emit a strictly validated single-model C++ phoneme table from Piper JSON.
Runs on the build host. No model data is generated by calling an external TTS API.
"""
import argparse
import json
import pathlib
import hashlib
import re

def symbols(config: dict):
    table = config["phoneme_id_map"]
    if not isinstance(table, dict) or len(table) < 100:
        raise ValueError("Piper phoneme map is incomplete")
    if config.get("phoneme_type") != "espeak":
        raise ValueError("Expected eSpeak Piper voice")
    if config.get("audio", {}).get("sample_rate") != 22050:
        raise ValueError("Expected 22050 Hz Thorsten model")
    for key, expected in (("_", 0), ("^", 1), ("$", 2)):
        if table.get(key) != [expected]:
            raise ValueError(f"Invalid reserved Piper id: {key}")
    entries = []
    values = []
    for character, ids in sorted(table.items(), key=lambda p: ord(p[0])):
        if len(character) != 1 or not isinstance(ids, list) or not ids:
            raise ValueError("Invalid phoneme entry")
        if len(ids) > 255 or len(values) > 65535:
            raise ValueError("Too many Piper symbol IDs")
        if any(not isinstance(x, int) or not 0 <= x < 256 for x in ids):
            raise ValueError("Unexpected symbol ID")
        entries.append((ord(character), len(values), len(ids)))
        values += ids
    return entries, values

def generate(config_path, output, namespace="", expected_language=None):
    if not re.fullmatch(r"[a-zA-Z_][a-zA-Z_0-9]*",namespace or "default_"):
        raise ValueError("Invalid C++ namespace")
    payload=pathlib.Path(config_path).read_bytes()
    obj=json.loads(payload)
    if expected_language and obj.get("language",{}).get("code")!=expected_language:
        raise ValueError(f"Wrong language for voice: expected {expected_language}")
    if obj.get("num_speakers") != 1:
        raise ValueError("Use only single-speaker Piper models (no optional sid tensor)")
    items, ids=symbols(obj)
    lines=[
        "// Generated from Piper Thorsten medium JSON; DO NOT EDIT.",
        "// SHA256 input JSON: "+hashlib.sha256(payload).hexdigest(),
        "#pragma once",
        '#include "phoneme_ids.hpp"',
        "#include <array>",
        "namespace bible_piper {"+(" namespace "+namespace+" {" if namespace else ""),
        f"inline constexpr std::array<Symbol,{len(items)}> kThorstenSymbols{{{{",
    ]
    lines += [f"  {{0x{code:04X},{offset},{count}}}," for code,offset,count in items]
    lines += [
        "}};",
        f"inline constexpr std::array<std::int64_t,{len(ids)}> kThorstenValues{{{{",
    ]
    lines += [f"  {value}," for value in ids]
    lines += [
        "}};",
        "inline constexpr PhonemeTable thorstenTable(){",
        " return {kThorstenSymbols.data(),kThorstenSymbols.size(),",
        "         kThorstenValues.data(),kThorstenValues.size()};",
        "}",
        "}"+(" }" if namespace else ""),
    ]
    pathlib.Path(output).write_text("\n".join(lines)+"\n",encoding="utf-8")
    print(f"Generated Thorsten Piper table with {len(items)} phonemes and {len(ids)} ids")

def main():
    parser=argparse.ArgumentParser()
    parser.add_argument("config",type=pathlib.Path)
    parser.add_argument("output",type=pathlib.Path)
    parser.add_argument("--namespace",default="")
    parser.add_argument("--expected-language",default=None)
    a=parser.parse_args()
    generate(a.config,a.output,a.namespace,a.expected_language)

if __name__=="__main__":
    main()
