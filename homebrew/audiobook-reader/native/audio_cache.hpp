#pragma once
// Only disposable Audiobook Reader USB-cache files are ever evicted.
// Never recurse and never touch /data/AudioBookReader/Books, settings or logs.
#include <algorithm>
#include <cctype>
#include <cstdint>
#include <ctime>
#include <dirent.h>
#include <string>
#include <sys/stat.h>
#include <vector>
#include <cstdio>

namespace audio_cache {
constexpr uint64_t kBudgetBytes=8ULL*1024ULL*1024ULL*1024ULL;
struct Result {size_t removed=0;uint64_t bytes=0;bool complete=false;};
inline bool managed_name(const std::string& name){
 if(name.size()<24 || name.compare(0,4,"usb-")!=0)return false;
 for(size_t i=4;i<20;i++){
   const unsigned char c=(unsigned char)name[i];
   if(!((c>='0'&&c<='9')||(c>='a'&&c<='f')))return false;
 }
 const std::string ext=name.substr(20);
 return ext==".m4b";
}
inline Result prune(const std::string& folder,uint64_t incoming,
                    const std::string& keep="",uint64_t budget=kBudgetBytes){
 struct Item {std::string path;uint64_t size;time_t modified;};
 std::vector<Item> items;
 uint64_t total=0;
 DIR* d=opendir(folder.c_str());
 if(!d)return {};
 while(auto* e=readdir(d)){
   const std::string name=e->d_name;
   bool isPartial=false;
   if(!managed_name(name)){
     // Only remove interrupted transfers generated by this app. They are
     // never complete books and cannot be resumed across process restarts.
     if(name.size()>5 && name.compare(name.size()-5,5,".part")==0 &&
        managed_name(name.substr(0,name.size()-5)))isPartial=true;
     else continue;
   }
   const std::string path=folder+"/"+name;
   struct stat st{};
   if(stat(path.c_str(),&st)!=0||!S_ISREG(st.st_mode)||st.st_size<0)continue;
   const uint64_t bytes=(uint64_t)st.st_size;
   total+=bytes;
   if(isPartial){
     // Interrupted .part files may be much larger than available quota.
     // No other process can write them while the reader's transfer lock
     // is held, and their exact generated name has been validated.
     if(std::remove(path.c_str())==0)total-=bytes;
   }else if(path!=keep)items.push_back({path,bytes,st.st_mtime});
 }
 closedir(d);
 std::sort(items.begin(),items.end(),[](const Item& a,const Item& b){
    return a.modified==b.modified?a.path<b.path:a.modified<b.modified;
 });
 const uint64_t required=incoming>budget?0:budget-incoming;
 Result result;
 for(const auto& file:items){
   if(total<=required)break;
   if(std::remove(file.path.c_str())==0){
      total-=file.size;result.bytes+=file.size;result.removed++;
   }
 }
 result.complete=total<=required;
 return result;
}
} // namespace audio_cache
