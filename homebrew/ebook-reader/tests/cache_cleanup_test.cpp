#include "ebook_cache.hpp"
#include <cassert>
#include <cstdio>
#include <string>
#include <sys/stat.h>
#include <unistd.h>
#include <utime.h>
static void file(const std::string& name,size_t bytes){
 FILE* f=fopen(name.c_str(),"wb");assert(f);
 char block[1024]={};
 for(size_t i=0;i<bytes/sizeof(block);i++)assert(fwrite(block,1,sizeof(block),f)==sizeof(block));
 assert(fclose(f)==0);
}
static bool exists(const std::string& name){return access(name.c_str(),F_OK)==0;}
int main(){
 const std::string root="/tmp/ebook-cache-prune-test";
 const std::string cache=root+"/Cache",books=root+"/Books";
 mkdir(root.c_str(),0700);mkdir(cache.c_str(),0700);mkdir(books.c_str(),0700);
 // Only exact names generated by the application may be deleted.
 assert(ebook_cache::managed_name("usb-0123456789abcdef.cbr"));
 assert(ebook_cache::managed_name("usb-0123456789abcdef.cbz"));
 assert(!ebook_cache::managed_name("usb-1234.cbr"));
 assert(!ebook_cache::managed_name("usb-0123456789abcdef.cbr.part"));
 assert(!ebook_cache::managed_name("../Books/original.cbr"));
 assert(!ebook_cache::managed_name("usb-0123456789abcdef.cbr.bak"));
 const auto a=cache+"/usb-0000000000000001.cbr";
 const auto b=cache+"/usb-0000000000000002.cbz";
 const auto c=cache+"/usb-0000000000000003.epub";
 const auto partial=cache+"/usb-0000000000000004.cbr.part";
 const auto other=cache+"/unrelated.bin";
 const auto userBook=books+"/original.cbr";
 const auto settings=root+"/library.tsv";
 file(a,4*1024*1024);file(b,4*1024*1024);file(c,4*1024*1024);
 file(partial,2*1024*1024);
 file(other,2*1024*1024);
 file(userBook,4*1024*1024);
 file(settings,1024);
 const auto result=ebook_cache::prune(cache,4*1024*1024,"",9*1024*1024);
 assert(result.complete);
 assert(result.removed==2);
 assert(result.bytes==8*1024*1024);
 assert(!exists(a)&&!exists(b)&&exists(c));
 assert(!exists(partial));
 assert(exists(other)&&exists(userBook)&&exists(settings));
 // Keep active book if requested even when the cache's budget is tiny.
 const auto keep=ebook_cache::prune(cache,100*1024*1024,c,9*1024*1024);
 assert(!keep.complete && exists(c));
 puts("Safe USB comic cache eviction and abandoned-part cleanup passed");
}
